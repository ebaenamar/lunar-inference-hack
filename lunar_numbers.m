function T = lunar_numbers(cfg, C, outFile)
%LUNAR_NUMBERS Every number of the pitch, from the simulation, written to NUMBERS.md.
%   1. Strategies (same fleet, work, orbits; only the placement changes).
%   2. The three layers of distribution: inference, reasoning, allocation.
%   3. Fleet architectures: base hardware, constellation density, slow tier on the
%      ground or in Earth orbit, at 100 and 500 robots.

if nargin < 3, outFile = 'NUMBERS.md'; end
P = tier_prices(cfg, C);
fid = fopen(outFile,'w'); cl = onCleanup(@() fclose(fid));
w = @(varargin) fprintf(fid, varargin{:});
w('# Numbers\n\nGenerated by `lunar_numbers.m` from the simulation. %s, %d days, %s launch price ($%s/kg to the lunar surface).\n\n', ...
    cfg.site, cfg.days, cfg.launchPrice, commas(P.usdPerKg));
w('Energy prices: robot ~$%.0f/kWh, relays ~$%.0f/kWh, lunar base ~$%.0f/kWh, Earth grid $%.3f/kWh on average, ', ...
    P.robot, P.relay, P.base, cfg.earthUSDperkWh);
co = earth_tier(setfield(cfg,'earthTier','Orbit')); %#ok<SFLD>
w('Earth orbit ~$%.2f/kWh (launch to LEO at $%s/kg).\n\n', co.earthUSDperkWh, commas(cfg.leoUSDperKg));

% ---------------- 1. Strategies
L = lunar_savings(cfg, C, false);
tot = sum(L.USD,2);
w('## 1. Strategies (%d robots, %d relay(s), lunar base %s)\n\n', cfg.nRobots, cfg.nRelays, cfg.baseHW);
w('Energy bill = all the energy the compute draws on each tier (work, idle GPUs, cooling, radio) times that tier''s $/kWh. Work only = the energy of the requests alone.\n\n');
w('| Strategy | Base hardware | Energy bill $/robot-day | Work only $/robot-day | Perception / tactical / deep on time | Deep by Kimi K3 | Lunar base peak | Lunar kWh/robot-day |\n|---|---|---|---|---|---|---|---|\n');
for s = 1:numel(L.strategies)
    hw = L.hw{s}; if isempty(hw), hw = 'Thor per robot'; end
    if strcmp(L.strategies{s},'AllOnEarth'), hw = 'none'; end
    w('| %s | %s | **%s** | %s | %.0f / %.0f / %.0f %% | %.0f %% | %.1f kW | %.2f |\n', L.strategies{s}, hw, commas(tot(s)), ...
        commas(L.margUSD(s)), 100*L.served(s,1), 100*L.served(s,2), 100*L.served(s,3), 100*L.served(s,4), L.peakKW(s), sum(L.kWh(s,1:4)));
end
w('\nCoordinated vs Moon-first: **%.1fx** cheaper. Coordinated vs all on the Moon: **%.1fx** cheaper, peak %.1f kW instead of %.1f kW, power plant $%.0f M instead of $%.0f M to launch.\n\n', ...
    tot(4)/tot(5), tot(3)/tot(5), L.peakKW(5), L.peakKW(3), L.plantUSD(5)/1e6, L.plantUSD(3)/1e6);
T.strategies = L;

% ---------------- 2. Layers
r = L.res{5}; ts = r.ts; cc = r.cost; nd = cfg.days*cfg.nRobots;
frames = sum(ts.arrPer);
gated = sum(ts.boardJ - ts.tacBoard*cc.small.energyJ)/cfg.detectorJ;                     % frames answered on board
act = geo_act(r); jp = ts.jPer(act); bp = ts.batchPer(act);
dec = [sum(ts.tacBoard) sum(ts.tacRelay) sum(ts.tacBase) sum(ts.tacEarth)]; decTot = sum(dec);
eJ = ts.earthJ > 0;
siteShare = accumarray(ts.earthSite(eJ)', ts.earthJ(eJ)', [numel(r.earthSiteNames) 1])/max(sum(ts.earthJ),eps);
w('## 2. Three layers of distribution (Coordinated)\n\n');
w('**Distributed inference: one request flows through several nodes.**\n\n');
w('- %.0f %% of camera frames are screened by the on-board detector and never leave the robot; the rest go to the 7B model at the base.\n', 100*gated/max(frames,1));
w('- Deadline-aware batching at the base: batch %.0f to %.0f, %.0f J per frame on average against %.0f J unbatched.\n', ...
    min(bp), max(bp), mean(jp), r.batchTables.perBase.J(1));
w('- Each relay runs a full replica of the 30B model; splitting a model by layers across relays would add tens of ms per token (JARVIS).\n\n');
w('**Distributed reasoning: the same decision is thought fast on the Moon and slow on Earth.**\n\n');
w('- Every tactical decision gets a fast answer on the Moon; %.1f %% of them, the ones the fast model is unsure about, also go to Kimi K3 on Earth.\n', 100*r.escRate);
w('- Kimi K3''s answer arrives %.1f min later on average (store and forward).\n', r.corrMin);
w('- Wrong decisions drop from %.1f %% to %.1f %%: %.1f corrections per robot-day (assumed error rates in `lunar_config.m`).\n\n', ...
    100*r.errFast, 100*r.errFinal, r.fixPerRobotDay);
w('**Distributed allocation across data centers: each request goes to the cheapest node that meets its deadline.**\n\n');
w('- Tactical decisions served by: robot %.1f %%, relays %.1f %%, lunar base %.1f %%, Earth %.1f %%.\n', 100*dec/max(decTot,eps));
w('- Earth work by site: %s.\n', strjoin(arrayfun(@(k) sprintf('%s %.0f %%', r.earthSiteNames{k}, 100*siteShare(k)), 1:numel(siteShare), 'Uni',0), ', '));
w('- Lunar base: %.2f kW average, %.1f kW peak, GPUs busy %.0f %% of the time on average.\n\n', r.baseAvgKW, max(ts.baseKW), 100*mean(ts.util(act)));

% ---------------- 3. Architectures
A = {'DGX B200 base, first relay',            'DGX-B200', 1, 'Ground'
     'DGX B200 base, full LCRNS (5 relays)',  'DGX-B200', 5, 'Ground'
     'small servers, 5 relays',               'small', 5, 'Ground'
     'small servers, dense constellation (15 relays)', 'small', 15, 'Ground'
     'DGX B200, dense constellation (15 relays)', 'DGX-B200', 15, 'Ground'
     'small servers, 5 relays, slow tier in Earth orbit', 'small', 5, 'Orbit'};
w('## 3. Fleet architectures (Coordinated)\n\n');
w('| Robots | Architecture | Energy bill $/robot-day | Launch $/robot-day | Perception / tactical / deep on time | Wrong decisions | Base avg / peak | Relays avg | Earth $ / CO2 (30 d) | Mass to the Moon |\n|---|---|---|---|---|---|---|---|---|---|\n');
T.arch = struct('robots',{},'name',{},'bill',{},'launch',{});
for nr = [100 500]
    for k = 1:size(A,1)
        c = cfg; c.nRobots = nr; c.baseHW = A{k,2};
        if strcmp(c.baseHW,'small'), c.baseHW = sprintf('%dxRTX-PRO', 3 + 5*(nr > 100)); end   % 3 servers for 100 robots, 8 for 500
        c.nRelays = A{k,3}; c.earthTier = A{k,4}; c.policy = 'Coordinated';
        g = lunar_geometry(c); rr = lunar_dispatch(c, g, C); e = lunar_economics(c, rr);
        relKg = e.relayMassKg*(c.nRelays > 0);
        launch = (e.launchUSD + relKg*e.usdPerKg)/(c.lifeYears*365.25)/nr;
        nm = strrep(A{k,1}, 'small servers', sprintf('%s small servers', c.baseHW(1:find(c.baseHW=='x')-1)));
        w('| %d | %s | **%s** | %s | %.0f / %.0f / %.0f %% | %.1f %% | %.2f / %.1f kW | %.0f W | $%s / %.0f kg | %s kg |\n', nr, nm, ...
            commas(e.billUSDperDay/nr), commas(launch), 100*rr.perOnTime, 100*rr.tacOnTime, 100*rr.deepOnTime, 100*rr.errFinal, ...
            rr.baseAvgKW, max(rr.ts.baseKW), mean(rr.ts.relayW), commas(rr.earthUSD), rr.earthCO2kg, commas(e.mass.total + relKg));
        T.arch(end+1) = struct('robots',nr,'name',A{k,1},'bill',e.billUSDperDay/nr,'launch',launch);
    end
end
w('\nLaunch $/robot-day = launch of the base (compute, power plant sized to the measured peak, radiators) and of the relay compute payloads, over %d years.\n', cfg.lifeYears);
fprintf('Wrote %s\n', outFile);
end

function a = geo_act(r)
a = r.ts.batchPer > 0 & r.ts.arrPer > 0;
end

function s = commas(x)
if abs(x) >= 100, s = regexprep(sprintf('%.0f', x), '\d(?=(\d{3})+$)', '$0,');
elseif abs(x) >= 10, s = sprintf('%.0f', x);
else, s = sprintf('%.1f', x); end
end
